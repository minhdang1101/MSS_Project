-- Schema for every service database. Mirrors the JPA entities exactly, so Hibernate
-- (ddl-auto=update) finds nothing to change and ddl-auto=validate passes.
-- Safe to re-run: every object uses IF NOT EXISTS.
-- Run with psql (uses \connect):  psql -U <user> -f 01-schema.sql

-- ===================== catalog_db (book-catalog-service) =====================
\connect catalog_db

CREATE TABLE IF NOT EXISTS book (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn             varchar(20)  NOT NULL UNIQUE,
    title            varchar(255) NOT NULL,
    author           varchar(255) NOT NULL,
    publisher        varchar(255),
    publication_year integer,
    category         varchar(100),
    language         varchar(50),
    format           varchar(20)  NOT NULL CHECK (format IN ('PHYSICAL', 'DIGITAL')),
    total_copies     integer      NOT NULL CHECK (total_copies >= 0),
    available_copies integer      NOT NULL CHECK (available_copies >= 0),
    status           varchar(20)  NOT NULL CHECK (status IN ('AVAILABLE', 'UNAVAILABLE', 'ARCHIVED')),
    version          bigint,
    created_at       timestamp(6) with time zone NOT NULL,
    updated_at       timestamp(6) with time zone NOT NULL,
    CONSTRAINT book_available_le_total CHECK (available_copies <= total_copies)
);

-- Cover picture, in its own table so listing books never loads image bytes. One per book; a new upload replaces it.
CREATE TABLE IF NOT EXISTS book_cover (
    book_id      bigint PRIMARY KEY REFERENCES book (id),
    content_type varchar(30) NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png')),
    data         bytea       NOT NULL,
    updated_at   timestamp(6) with time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS book_copy (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id        bigint      NOT NULL REFERENCES book (id),
    barcode        varchar(50) NOT NULL UNIQUE,
    shelf_location varchar(50),
    status         varchar(20) NOT NULL CHECK (status IN ('AVAILABLE', 'RESERVED', 'ON_LOAN', 'LOST', 'DAMAGED'))
);
CREATE INDEX IF NOT EXISTS idx_book_copy_book_status ON book_copy (book_id, status);

CREATE TABLE IF NOT EXISTS reservation (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id     bigint       NOT NULL REFERENCES book (id),
    copy_id     bigint       REFERENCES book_copy (id),
    request_key varchar(100) NOT NULL UNIQUE,
    status      varchar(20)  NOT NULL CHECK (status IN ('HELD', 'RELEASED', 'CONFIRMED', 'EXPIRED')),
    expires_at  timestamp(6) with time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_reservation_status_expires ON reservation (status, expires_at);

-- Inbox: an event already handled by a consumer is skipped on redelivery
CREATE TABLE IF NOT EXISTS processed_event (
    event_id     varchar(100) NOT NULL,
    consumer     varchar(100) NOT NULL,
    processed_at timestamp(6) with time zone NOT NULL,
    PRIMARY KEY (event_id, consumer)
);

-- ===================== member_db (member-service) =====================
\connect member_db

CREATE TABLE IF NOT EXISTS member (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_card_no varchar(30)  NOT NULL UNIQUE,
    full_name       varchar(150) NOT NULL,
    email           varchar(150) NOT NULL UNIQUE,
    phone           varchar(20) UNIQUE,
    status          varchar(20)  NOT NULL CHECK (status IN ('ACTIVE', 'SUSPENDED', 'LOCKED')),
    joined_at       date         NOT NULL,
    -- BCrypt hash of the reader login password; NULL until a librarian issues one (then the member cannot log in)
    password_hash   varchar(100),
    created_at      timestamp(6) with time zone NOT NULL,
    updated_at      timestamp(6) with time zone NOT NULL
);

-- Email is unique ignoring case (the plain UNIQUE above is case-sensitive, so A@x.com and a@x.com would both fit)
CREATE UNIQUE INDEX IF NOT EXISTS uk_member_email_lower ON member (lower(email));

-- Staff accounts. Rows are created by member-service at startup (app.bootstrap.librarian.*), never seeded here
-- because the password hash must come from configuration.
CREATE TABLE IF NOT EXISTS librarian (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_code    varchar(30)  NOT NULL UNIQUE,
    full_name     varchar(150) NOT NULL,
    password_hash varchar(100) NOT NULL,
    active        boolean      NOT NULL DEFAULT true,
    created_at    timestamp(6) with time zone NOT NULL,
    updated_at    timestamp(6) with time zone NOT NULL
);

-- ===================== loan_db (loan-service) =====================
\connect loan_db

-- member_id, book_id, copy_id point into other services' databases: no foreign keys
CREATE TABLE IF NOT EXISTS loan (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key varchar(100) NOT NULL UNIQUE,
    member_id       bigint       NOT NULL,
    book_id         bigint       NOT NULL,
    copy_id         bigint,
    loan_type       varchar(20)  NOT NULL CHECK (loan_type IN ('PHYSICAL', 'DIGITAL')),
    borrowed_at     timestamp(6) with time zone NOT NULL,
    due_at          timestamp(6) with time zone NOT NULL,
    returned_at     timestamp(6) with time zone,
    status          varchar(20)  NOT NULL CHECK (status IN ('BORROWED', 'OVERDUE', 'RETURNED')),
    -- set when LoanDueSoon was emitted, so the daily scan reminds only once per loan
    due_soon_notified_at timestamp(6) with time zone,
    version         bigint,
    created_at      timestamp(6) with time zone NOT NULL,
    updated_at      timestamp(6) with time zone NOT NULL,
    CONSTRAINT loan_due_after_borrow CHECK (due_at > borrowed_at),
    CONSTRAINT loan_returned_has_date CHECK ((status = 'RETURNED') = (returned_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_loan_member_status ON loan (member_id, status);
-- Scheduler scans open loans by due date for reminders and overdue marking
CREATE INDEX IF NOT EXISTS idx_loan_open_due ON loan (due_at) WHERE status <> 'RETURNED';

-- Transactional outbox, relayed to RabbitMQ after commit
CREATE TABLE IF NOT EXISTS outbox_event (
    id           varchar(36) PRIMARY KEY,
    aggregate_id bigint      NOT NULL,
    event_type   varchar(50) NOT NULL,
    payload      text        NOT NULL,
    created_at   timestamp(6) with time zone NOT NULL,
    published    boolean     NOT NULL,
    published_at timestamp(6) with time zone
);
CREATE INDEX IF NOT EXISTS idx_outbox_unpublished ON outbox_event (created_at) WHERE NOT published;

-- ===================== fine_db (fine-service) =====================
\connect fine_db

CREATE TABLE IF NOT EXISTS fine_policy (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_rate     numeric(12, 2) NOT NULL CHECK (daily_rate >= 0),
    grace_days     integer        NOT NULL CHECK (grace_days >= 0),
    max_amount     numeric(12, 2) CHECK (max_amount >= 0),
    lost_book_fee  numeric(12, 2) NOT NULL CHECK (lost_book_fee >= 0),
    active         boolean        NOT NULL,
    effective_from date           NOT NULL
);
-- At most one active policy at a time
CREATE UNIQUE INDEX IF NOT EXISTS uq_fine_policy_one_active ON fine_policy (active) WHERE active;

-- One fine per loan: duplicate LoanReturned/LoanOverdue events cannot double-charge
-- loan_id, member_id and book_id point into other services' databases: no foreign keys.
-- policy_id is the rule version this fine was opened with (same database, so a real foreign key).
CREATE TABLE IF NOT EXISTS fine (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id       bigint         NOT NULL UNIQUE,
    member_id     bigint         NOT NULL,
    book_id       bigint         NOT NULL,
    due_at        timestamp(6) with time zone NOT NULL,
    returned_at   timestamp(6) with time zone,
    policy_id     bigint         NOT NULL REFERENCES fine_policy (id),
    overdue_days  integer        NOT NULL CHECK (overdue_days >= 0),
    daily_rate    numeric(12, 2) NOT NULL,
    amount        numeric(12, 2) NOT NULL CHECK (amount >= 0),
    status        varchar(20)    NOT NULL CHECK (status IN ('ACCRUING', 'UNPAID', 'PAID', 'WAIVED')),
    calculated_at timestamp(6) with time zone NOT NULL,
    paid_at       timestamp(6) with time zone,
    version       bigint,
    CONSTRAINT fine_paid_has_date CHECK ((status = 'PAID') = (paid_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_fine_member_status ON fine (member_id, status);

-- Days the library is closed: not counted as late
CREATE TABLE IF NOT EXISTS closed_day (
    closed_on date PRIMARY KEY,
    reason    varchar(200)
);

-- ===================== notification_db (notification-service) =====================
\connect notification_db

CREATE TABLE IF NOT EXISTS notification (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key varchar(100) NOT NULL UNIQUE,
    member_id       bigint       NOT NULL,
    loan_id         bigint,
    type            varchar(20)  NOT NULL CHECK (type IN ('DUE_SOON', 'OVERDUE')),
    channel         varchar(20)  NOT NULL CHECK (channel IN ('EMAIL', 'SMS', 'IN_APP')),
    recipient       varchar(150) NOT NULL,
    subject         varchar(255) NOT NULL,
    message         text         NOT NULL,
    scheduled_at    timestamp(6) with time zone NOT NULL,
    sent_at         timestamp(6) with time zone,
    status          varchar(20)  NOT NULL CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    -- when the reader opened it in the app; NULL while unread
    read_at         timestamp(6) with time zone
);
-- A reader's list: their notifications, newest first
CREATE INDEX IF NOT EXISTS idx_notification_member_scheduled ON notification (member_id, scheduled_at DESC);
CREATE INDEX IF NOT EXISTS idx_notification_pending ON notification (scheduled_at) WHERE status = 'PENDING';
